function policy(): MeteringPolicyRevisionDraft {
  const draft = rate();
  return {
    schemaVersion: draft.schemaVersion,
    tenantId: draft.tenantId,
    effectiveFrom: draft.effectiveFrom,
    sourceRef: draft.sourceRef,
    verifiedAt: draft.verifiedAt,
    profileRef: draft.profileRef,
    currencyCode: "XTS",
    multiplier: { numerator: "7", denominator: "5" },
    creditMicrosPerMinor: { numerator: "100", denominator: "1" },
    roundingVersion: "attempt-ceil-v1",
    failurePolicyRef: null,
  };
}
function command<Draft>(
  draft: Draft,
  publicationIdentity: string,
): MeteringPublicationCommand<Draft> {
  return {
    tenantId: "tenant-a",
    actorId: "actor-a",
    publicationIdentity,
    idempotencyKey: "key-a",
    reason: "synthetic fixture",
    draft,
  };
}
function range(
  lowerInclusive: string,
  upperExclusive: string | null,
): MeteringRateApplicability {
  return {
    kind: "range",
    dimension: "context",
    unit: "token",
    lowerInclusive,
    upperExclusive,
  };
}
function rateWithRows(
  rates: readonly MeteringRevisionRate[],
): MeteringRateRevisionDraft {
  return { ...rate(), rates };
}
function changed(
  base: unknown,
  path: readonly (string | number)[],
  value: unknown,
  remove = false,
): unknown {
  const copy: unknown = structuredClone(base);
  let target: unknown = copy;
  for (const key of path.slice(0, -1)) {
    if (target === null || typeof target !== "object")
      throw new Error("Invalid fixture path");
    target = Reflect.get(target, key);
  }
  const last = path.at(-1);
  if (target === null || typeof target !== "object" || last === undefined)
    throw new Error("Invalid fixture target");
  if (remove) Reflect.deleteProperty(target, last);
  else Reflect.set(target, last, value);
  return copy;
}

// A complete synthetic encoder control is collected even against the minimal RED seam.
describe("R81 revision golden bytes and pure scope", () => {
  it("callable legal control returns hashed JSON without resource dependencies", () => {
    const encoded = encodeMeteringRateRevisionDraft(rate());
    expect(typeof encoded.canonicalJson).toBe("string");
    expect(encoded.contentDigest).toBe(hash(encoded.canonicalJson));
  });
  it("matches approved rate bytes/hash and decodes reversibly", () => {
    expect(encodeMeteringRateRevisionDraft(rate())).toEqual({
      canonicalJson: RATE_JSON,
      contentDigest: RATE_HASH,
    });
    expect(decodeMeteringRateRevisionDraft(RATE_JSON)).toEqual(rate());
  });
  it("matches pending policy golden without inventing a failure policy", () => {
    expect(encodeMeteringPolicyRevisionDraft(policy())).toEqual({
      canonicalJson: POLICY_JSON,
      contentDigest: POLICY_HASH,
    });
    expect(decodeMeteringPolicyRevisionDraft(POLICY_JSON)).toEqual(policy());
    expect(
      decodeMeteringPolicyRevisionDraft(POLICY_JSON).failurePolicyRef,
    ).toBeNull();
    expect(
      Object.keys(encodeMeteringPolicyRevisionDraft(policy())).sort(),
    ).toEqual(["canonicalJson", "contentDigest"]);
  });
  it("retains the named failure-policy reference but provides no execution proof", () => {
    const draft = {
      ...policy(),
      failurePolicyRef: {
        version: "synthetic-pending-reference",
        artifactDigest: "a".repeat(64),
      },
    };
    const encoded = encodeMeteringPolicyRevisionDraft(draft);
    expect(decodeMeteringPolicyRevisionDraft(encoded.canonicalJson)).toEqual(
      draft,
    );
    expect(encoded.contentDigest).not.toBe(POLICY_HASH);
  });
  it("matches Unicode golden, preserves embedded BOM, decomposed text and spaces", () => {
    const draft = { ...rate(), tenantId: "\uFEFF租户 e\u0301" };
    const encoded = encodeMeteringRateRevisionDraft(draft);
    expect(encoded.contentDigest).toBe(
      "4b6230fa28488ae26056ba5fe43c8b3ed45c6ea7f2d29007cfa7495ee408a977",
    );
    expect(encoded.canonicalJson).toBe(
      RATE_JSON.replace('"tenant-a"', JSON.stringify(draft.tenantId)),
    );
    expect(
      decodeMeteringRateRevisionDraft(encoded.canonicalJson).tenantId,
    ).toBe(draft.tenantId);
    for (const tenantId of [
      draft.tenantId.trim(),
      draft.tenantId.normalize("NFC"),
      ` ${draft.tenantId} `,
    ])
      expect(
        encodeMeteringRateRevisionDraft({ ...draft, tenantId }).contentDigest,
      ).not.toBe(encoded.contentDigest);
  });
  it("uses JSON.stringify escapes and raw slash/Unicode including U+2028/U+2029", () => {
    const sourceRef = ' /路径\t\n"\\\u2028\u2029 ';
    const encoded = encodeMeteringRateRevisionDraft({ ...rate(), sourceRef });
    expect(encoded.canonicalJson).toBe(
      RATE_JSON.replace('"synthetic-source"', JSON.stringify(sourceRef)),
    );
    expect(
      decodeMeteringRateRevisionDraft(encoded.canonicalJson).sourceRef,
    ).toBe(sourceRef);
  });
  it("ignores object property order and explicitly sorts the rate set without mutating input", () => {
    const draft = rate();
    const reversed = { ...draft, rates: [...draft.rates].reverse() };
    const reordered = Object.fromEntries(Object.entries(reversed).reverse());
    expect(encodeMeteringRateRevisionDraft(reordered).canonicalJson).toBe(
      RATE_JSON,
    );
    expect(reversed.rates.map((r) => r.bucket)).toEqual(["output", "input"]);
  });
  it("accepts null-prototype and frozen plain data without retaining mutable input aliases", () => {
    const draft = rate();
    Object.setPrototypeOf(draft, null);
    Object.freeze(draft);
    const encoded = encodeMeteringRateRevisionDraft(draft);
    const decoded = decodeMeteringRateRevisionDraft(encoded.canonicalJson);
    expect(decoded).toEqual(rate());
    expect(decoded.profileRef).not.toBe(draft.profileRef);
    expect(decoded.rates).not.toBe(draft.rates);
  });
});

